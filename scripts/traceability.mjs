#!/usr/bin/env node
/**
 * Requirements traceability.
 *
 * Reads the use case ids from docs/use-cases.md, finds every test whose name
 * carries an id (Jest, node:test and Deno tests), and:
 *   - fails if a use case has no test, or a test names an id that doesn't exist
 *   - with --write, regenerates docs/traceability.md
 *   - without --write, fails if docs/traceability.md is out of date
 *
 * Usage: node scripts/traceability.mjs [--write]
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = join(import.meta.dirname, '..');
const useCasesFile = join(root, 'docs', 'use-cases.md');
const matrixFile = join(root, 'docs', 'traceability.md');

const TEST_DIRS = [
  { dir: 'src', level: 'Unit (Jest)', match: /\.test\.tsx?$/ },
  { dir: 'supabase/tests', level: 'Database (Postgres)', match: /\.test\.mts$/ },
  { dir: 'supabase/functions/tests', level: 'Edge Function (Deno)', match: /\.test\.ts$/ },
];

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules') continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

const useCases = [...readFileSync(useCasesFile, 'utf8').matchAll(/^### (UC-\d{2}) (.+)$/gm)].map((m) => ({ id: m[1], title: m[2] }));
const known = new Set(useCases.map((u) => u.id));

/** @type {Map<string, {level: string, file: string, name: string}[]>} */
const byUseCase = new Map(useCases.map((u) => [u.id, []]));
const unknown = [];

for (const { dir, level, match } of TEST_DIRS) {
  for (const file of walk(join(root, dir)).filter((f) => match.test(f))) {
    const source = readFileSync(file, 'utf8');
    // it('...'), it.each(...)('...'), Deno.test('...')
    for (const m of source.matchAll(/(?:\bit(?:\.each\([^)]*\))?|Deno\.test)\(\s*'([^']+)'/g)) {
      for (const id of m[1].match(/UC-\d{2}/g) ?? []) {
        if (!known.has(id)) unknown.push(`${relative(root, file)}: ${id}`);
        else byUseCase.get(id).push({ level, file: relative(root, file), name: m[1] });
      }
    }
  }
}

const missing = useCases.filter((u) => byUseCase.get(u.id).length === 0);

const levels = TEST_DIRS.map((d) => d.level);
const lines = [
  '# Traceability matrix',
  '',
  'Generated by `node scripts/traceability.mjs --write` from [use-cases.md](use-cases.md) and the test names. CI fails if this file is out of date or a use case has no test.',
  '',
  `| Use case | ${levels.join(' | ')} | Total |`,
  `|---|${levels.map(() => '---:').join('|')}|---:|`,
];
for (const u of useCases) {
  const tests = byUseCase.get(u.id);
  const counts = levels.map((l) => tests.filter((t) => t.level === l).length);
  lines.push(`| ${u.id} ${u.title} | ${counts.join(' | ')} | ${tests.length} |`);
}
lines.push('', '## Tests by use case', '');
for (const u of useCases) {
  lines.push(`### ${u.id} ${u.title}`, '');
  for (const t of byUseCase.get(u.id)) lines.push(`- ${t.level}, \`${t.file}\`: ${t.name}`);
  lines.push('');
}
const matrix = lines.join('\n');

let failed = false;
if (missing.length) {
  console.error(`Use cases with no test: ${missing.map((u) => u.id).join(', ')}`);
  failed = true;
}
if (unknown.length) {
  console.error(`Tests naming a use case that doesn't exist:\n  ${unknown.join('\n  ')}`);
  failed = true;
}

if (process.argv.includes('--write')) {
  writeFileSync(matrixFile, matrix);
  console.log(`Wrote ${relative(root, matrixFile)}`);
} else {
  let current = '';
  try {
    current = readFileSync(matrixFile, 'utf8');
  } catch {
    // missing file is reported below
  }
  if (current !== matrix) {
    console.error('docs/traceability.md is out of date. Run: node scripts/traceability.mjs --write');
    failed = true;
  }
}

const total = [...byUseCase.values()].reduce((sum, t) => sum + t.length, 0);
console.log(`${useCases.length} use cases, ${total} tagged tests, ${missing.length} uncovered.`);
process.exit(failed ? 1 : 0);
